-- ПЕРЕВІРЕНА РОЗКЛАДКА (31.08.2026): тултипи й меню трею працюють на ВСІХ ТРЬОХ.
-- Фізично: 27" зверху, ноутбук під ним, портретний праворуч.
--
-- Не міняти числа навмання. Hyprland 0.56.2 має баг з обмеженням xdg_popup
-- (https://github.com/hyprwm/Hyprland/issues/16075): попап втискається в коробку
-- сусіднього монітора й відкривається повз екран. У більшості розкладок робочим
-- лишався тільки один монітор. Саме ця комбінація виявилась цілком робочою —
-- ключове те, що HDMI-A-1 стоїть на x=128, тож його правий край (128+1920=2048)
-- збігається з правим краєм eDP-1 (3072/1.5=2048). При HDMI на x=0 попапи
-- на ноутбуці ламаються.
--
-- Значення отримані через nwg-displays; він переписує цей файл разом із цим
-- коментарем, тому числа продубльовані нижче для відновлення:
--   eDP-1     3072x1920@120  0x1080    scale 1.5
--   HDMI-A-1  1920x1080@100  128x0     scale 1
--   DP-2      1920x1080@100  2048x0    scale 1, transform 3

hl.monitor({
    output = "eDP-1",
    mode = "3072x1920@120.0",
    position = "0x1080",
    scale = 1.5
})
hl.monitor({
    output = "DP-2",
    mode = "1920x1080@100.0",
    position = "2048x0",
    scale = 1,
    transform = 3
})
hl.monitor({
    output = "HDMI-A-1",
    mode = "1920x1080@100.0",
    position = "128x0",
    scale = 1.0
})
